import { useRef, useState } from 'react';
import { FileUp, Trash2 } from 'lucide-react';
import { deleteRow, fmtDate, insertRow, updateRow, useQuery } from '../lib/data';
import { uploadFile, uploadUrl } from '../uploads';
import type { Doc } from '../lib/types';
import { Badge, Button, ErrorNote, Field, Input, Modal, Select, SourceLink, Textarea, useAsync } from './ui';

export const DOC_KINDS: Record<string, string> = {
  note: 'Research note', research: 'Market / competitor research', interview: 'Interview notes', correspondence: 'Correspondence', technical_evidence: 'Technical evidence',
  solicitation: 'Solicitation document', legal: 'Agreement / legal', source_text: 'Original source text', ai_summary: 'AI-generated summary', file: 'File',
};
type Scope = { project_id?: string | null; technology_id?: string | null; opportunity_id?: string | null; proposal_section_id?: string | null };

export function DocList({ scope, compact, kindFilter }: { scope: Scope; compact?: boolean; kindFilter?: string }) {
  const entries = Object.entries(scope).filter(([, v]) => v) as [string, string][];
  const key = entries.map(e => e.join('=')).join('&');
  const q = useQuery<Doc>('documents', b => { let x = b; for (const [k, v] of entries) x = x.eq(k, v); if (kindFilter) x = x.eq('kind', kindFilter); return x.order('created_at', { ascending: false }); }, [key, kindFilter], entries.length > 0);
  const [adding, setAdding] = useState(false);
  const [open, setOpen] = useState<Doc | null>(null);
  const fileRef = useRef<HTMLInputElement>(null);
  const { busy, error, run } = useAsync();

  const onFile = (f: File) => run(async () => {
    const up = await uploadFile(f);
    await insertRow('documents', { ...scope, kind: 'file', title: f.name, upload_id: up.id });
  });

  return (
    <div className="space-y-2">
      <div className="flex flex-wrap gap-2">
        <Button size="sm" onClick={() => setAdding(true)}>Add note</Button>
        <Button size="sm" busy={busy} onClick={() => fileRef.current?.click()}><FileUp className="size-3.5" />Attach file</Button>
        <input ref={fileRef} type="file" className="hidden" aria-label="Attach file" onChange={e => { const f = e.target.files?.[0]; if (f) void onFile(f); e.target.value = ''; }} />
      </div>
      <ErrorNote error={error} />
      {!q.data.length ? <p className="text-sm text-slate-500">{compact ? 'No notes or files attached.' : 'No documents yet.'}</p> : (
        <ul className="divide-y divide-slate-100 rounded-md border border-slate-200 bg-white">
          {q.data.map(d => (
            <li key={d.id} className="flex items-start justify-between gap-2 px-3 py-2 text-sm">
              <button type="button" className="min-w-0 text-left" onClick={() => d.upload_id ? void uploadUrl(d.upload_id).then(u => window.open(u, '_blank')) : setOpen(d)}>
                <div className="font-medium hover:underline">{d.title}</div>
                <div className="flex flex-wrap items-center gap-1.5 text-xs text-slate-500"><Badge>{DOC_KINDS[d.kind] ?? d.kind}</Badge>{d.is_ai_generated && <Badge tone="amber">AI-generated — not verified</Badge>}{fmtDate(d.created_at)}{d.source_url && <SourceLink url={d.source_url} />}</div>
                {!compact && d.body && <p className="mt-0.5 line-clamp-2 text-xs text-slate-600">{d.body}</p>}
              </button>
              <Button size="sm" variant="ghost" aria-label={`Delete ${d.title}`} onClick={() => { if (confirm(`Delete "${d.title}"?`)) void deleteRow('documents', d.id); }}><Trash2 className="size-3.5" /></Button>
            </li>
          ))}
        </ul>
      )}
      <Modal open={adding} onClose={() => setAdding(false)} title="Add a note or research record" wide><DocEditor scope={scope} onDone={() => setAdding(false)} /></Modal>
      <Modal open={!!open} onClose={() => setOpen(null)} title={open?.title ?? ''} wide>{open && <DocEditor scope={scope} doc={open} onDone={() => setOpen(null)} />}</Modal>
    </div>
  );
}

function DocEditor({ scope, doc, onDone }: { scope: Scope; doc?: Doc; onDone: () => void }) {
  const [v, setV] = useState({ title: doc?.title ?? '', kind: doc?.kind ?? 'note', body: doc?.body ?? '', source_url: doc?.source_url ?? '' });
  const { busy, error, run } = useAsync();
  const readonly = doc?.kind === 'source_text';
  return (
    <div className="space-y-3">
      {doc?.is_ai_generated && <p className="rounded bg-amber-50 p-2 text-xs text-amber-900">Generated by the assistant. Treat as a draft or hypothesis until you verify it.</p>}
      {readonly && <p className="rounded bg-slate-50 p-2 text-xs text-slate-600">Original source text is kept unchanged.</p>}
      <div className="grid gap-2 md:grid-cols-[1fr_14rem]">
        <Field label="Title"><Input aria-label="Document title" value={v.title} disabled={readonly} onChange={e => setV({ ...v, title: e.target.value })} /></Field>
        <Field label="Type"><Select aria-label="Document type" value={v.kind} disabled={readonly} onChange={e => setV({ ...v, kind: e.target.value })} options={Object.fromEntries(Object.entries(DOC_KINDS).filter(([k]) => k !== 'file' && k !== 'source_text' && k !== 'ai_summary'))} /></Field>
      </div>
      <Field label="Content"><Textarea aria-label="Document content" rows={14} readOnly={readonly} value={v.body} onChange={e => setV({ ...v, body: e.target.value })} /></Field>
      <Field label="Source URL (if any)"><Input aria-label="Document source URL" value={v.source_url} disabled={readonly} onChange={e => setV({ ...v, source_url: e.target.value })} /></Field>
      <ErrorNote error={error} />
      {!readonly && <Button variant="primary" busy={busy} disabled={!v.title.trim()} onClick={() => run(async () => {
        if (doc) await updateRow('documents', doc.id, { ...v, updated_at: new Date().toISOString() }); else await insertRow('documents', { ...scope, ...v });
        onDone();
      })}>Save</Button>}
    </div>
  );
}
